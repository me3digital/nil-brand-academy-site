// Builds one SQL file for the Supabase SQL Editor: every migration, the migration ledger, then the seed.
// Contains schema and public-source data only. No credentials.
import fs from 'node:fs';
const dir = 'db/migrations';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
let out = `-- NIL Intelligence Network: full deploy bundle. Generated by scripts/bundle-sql.mjs. Run once on an empty database.\nbegin;\ncreate table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());\n`;
for (const f of files) out += `\n-- ===== ${f}\n${fs.readFileSync(`${dir}/${f}`, 'utf8')}\ninsert into schema_migrations (name) values ('${f}');\n`;
out += `\n-- ===== seed\n${fs.readFileSync('db/seed/florida.generated.sql', 'utf8')}\ninsert into schema_migrations (name) values ('seed:florida');\nalter table schema_migrations enable row level security;\ncommit;\n`;
fs.mkdirSync('db/deploy', { recursive: true });
fs.writeFileSync('db/deploy/supabase_bundle.sql', out);
console.log('wrote db/deploy/supabase_bundle.sql', out.length, 'bytes');
